/**
 * Bundles docs/*.md into lib/legalBundles.ts for in-app display.
 * Run: node scripts/sync-legal-docs.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const docsDir = path.join(root, 'docs');
const outFile = path.join(root, 'lib', 'legalBundles.ts');

const FILES = {
  'privacy-policy': { en: 'privacy-policy-en.md', ka: 'privacy-policy-ka.md' },
  'terms-of-service': { en: 'terms-of-service-en.md', ka: 'terms-of-service-ka.md' },
};

function readDoc(filename) {
  const p = path.join(docsDir, filename);
  if (!fs.existsSync(p)) {
    throw new Error(`Missing legal doc: ${p}`);
  }
  return fs.readFileSync(p, 'utf8');
}

const bundles = {};
for (const [slug, locales] of Object.entries(FILES)) {
  bundles[slug] = {
    en: readDoc(locales.en),
    ka: readDoc(locales.ka),
  };
}

const header = `/** AUTO-GENERATED by scripts/sync-legal-docs.mjs — do not edit manually */\n`;
const body = `export const LEGAL_BUNDLES = ${JSON.stringify(bundles, null, 2)} as const;\n\nexport type LegalDocSlug = keyof typeof LEGAL_BUNDLES;\nexport type LegalDocLocale = 'en' | 'ka';\n`;

fs.writeFileSync(outFile, header + body, 'utf8');
console.log('Wrote', outFile);
